template <typename Derived>
MStatus RigModuleWithControlsNode<Derived>::initializeSharedAttributes()
{
	MStatus status = Base::initializeSharedAttributes();   // RigModuleNode<Derived>
	CHECK_MSTATUS_AND_RETURN_IT(status);

	MFnMatrixAttribute mAttr;
	MFnMessageAttribute msgAttr;
	MFnCompoundAttribute cAttr;
	MFnTypedAttribute tAttr;

	aControlMatrix = mAttr.create(RigAttr::ControlLocalMatrix, RigAttr::ControlLocalMatrix, MFnMatrixAttribute::kDouble, &status);
	CHECK_MSTATUS_AND_RETURN_IT(status);

	aControlRestWorld = mAttr.create(RigAttr::ControlRestWorld, RigAttr::ControlRestWorld, MFnMatrixAttribute::kDouble, &status);
	CHECK_MSTATUS_AND_RETURN_IT(status);
	mAttr.setStorable(true);

	aControlInputData = cAttr.create(RigAttr::ControlInputData, RigAttr::ControlInputData, &status);
	CHECK_MSTATUS_AND_RETURN_IT(status);
	cAttr.addChild(aControlMatrix);
	cAttr.addChild(aControlRestWorld);
	cAttr.setArray(true);
	cAttr.setUsesArrayDataBuilder(true);
	CHECK_MSTATUS_AND_RETURN_IT(Base::addAttribute(aControlInputData));
	
	// Compound attribute for child plugs
	aChildPlugName = tAttr.create(RigAttr::ChildPlugName, RigAttr::ChildPlugName, MFnData::kString, MObject::kNullObj, &status);
	CHECK_MSTATUS_AND_RETURN_IT(status);
	tAttr.setStorable(true);

	aChildPlugParentMatrix = mAttr.create(RigAttr::ChildPlugParentMatrix, RigAttr::ChildPlugParentMatrix, MFnMatrixAttribute::kDouble, &status);
	CHECK_MSTATUS_AND_RETURN_IT(status);

	aChildPlugParentRestMatrix = mAttr.create(RigAttr::ChildPlugParentRestMatrix, RigAttr::ChildPlugParentRestMatrix, MFnMatrixAttribute::kDouble, &status);
	CHECK_MSTATUS_AND_RETURN_IT(status);
	mAttr.setStorable(true);

	aChildPlugs = cAttr.create(RigAttr::ChildPlugs, RigAttr::ChildPlugs, &status);
	CHECK_MSTATUS_AND_RETURN_IT(status);

	cAttr.addChild(aChildPlugName);
	cAttr.addChild(aChildPlugParentMatrix);
	cAttr.addChild(aChildPlugParentRestMatrix);
	cAttr.setArray(true);
	cAttr.setUsesArrayDataBuilder(true);
	CHECK_MSTATUS_AND_RETURN_IT(Base::addAttribute(aChildPlugs));

	aControlOPM = mAttr.create(RigAttr::ControlOPM, RigAttr::ControlOPM, MFnMatrixAttribute::kDouble, &status);
	CHECK_MSTATUS_AND_RETURN_IT(status);
	mAttr.setArray(true);
	mAttr.setWritable(false);
	mAttr.setStorable(false);
	mAttr.setUsesArrayDataBuilder(true);
	CHECK_MSTATUS_AND_RETURN_IT(Base::addAttribute(aControlOPM));

	aControlMessage = msgAttr.create(RigAttr::ControlMessage, RigAttr::ControlMessage, &status);
	CHECK_MSTATUS_AND_RETURN_IT(status);
	msgAttr.setArray(true);
	CHECK_MSTATUS_AND_RETURN_IT(Base::addAttribute(aControlMessage));

	// Output Socket Matrix Array
	aOutputSocketMatrix = mAttr.create(RigAttr::OutputSocketMatrix, RigAttr::OutputSocketMatrix, MFnMatrixAttribute::kDouble, &status);
	mAttr.setArray(true);
	mAttr.setUsesArrayDataBuilder(true);
	mAttr.setWritable(false);
	mAttr.setStorable(false);
	mAttr.setWorldSpace(true);
	CHECK_MSTATUS_AND_RETURN_IT(Base::addAttribute(aOutputSocketMatrix));

	// Socket names array
	aSocketNames = tAttr.create(RigAttr::SocketNames, RigAttr::SocketNames, MFnData::kString, MObject::kNullObj, &status);
	tAttr.setStorable(true);
	tAttr.setArray(true);
	CHECK_MSTATUS_AND_RETURN_IT(Base::addAttribute(aSocketNames));

	return MStatus::kSuccess;
}

template <typename Derived>
MStatus RigModuleWithControlsNode<Derived>::connectSocketMatrixToChildPlug(
	const MObject& oChildModule,
	unsigned int childPlugIndex,
	const MObject& oParentModule,
	unsigned int parentSocketIndex,
	const MMatrix& mSocketRest,
	MDagModifier& dagMod)
{
	MStatus status;

	MPlug pChildPlugParentMatrix;
	MPlug pChildPlugParentRest;
	status = RigModuleNodeBase::getChildPlugMatrixPlugs(oChildModule, childPlugIndex, pChildPlugParentMatrix, pChildPlugParentRest);
	CHECK_MSTATUS_AND_RETURN_IT(status);

	MPlug pParentSocketMatrix = RigModuleNodeBase::getSocketMatrixPlug(oParentModule, parentSocketIndex, &status);
	CHECK_MSTATUS_AND_RETURN_IT(status);

	// Rest comes from pass 1 data. Live == rest at connection time, so the delta is identity.
	DagUtils::setMatrixPlug(pChildPlugParentRest, mSocketRest, dagMod);
	return dagMod.connect(pParentSocketMatrix, pChildPlugParentMatrix);
}

template <typename Derived>
MStatus RigModuleWithControlsNode<Derived>::solveFkChain(
	MDataBlock& data,
	MArrayDataHandle& hControlInputData,
	MArrayDataHandle& hOutputData,
	const unsigned int& childPlugIndex,
	const bool& useLocalMatrix
)
{
	MStatus status;

	MArrayDataHandle hChildPlugs = data.inputArrayValue(aChildPlugs, &status);
	CHECK_MSTATUS_AND_RETURN_IT(status);

	// Motion of the chain's parent socket since rest. Identity if unparented.
	MMatrix mParentDelta = readChildPlugParentDelta(hChildPlugs, childPlugIndex);

	const unsigned int elementCount = hControlInputData.elementCount();

	for (unsigned int i = 0; i < elementCount; ++i)
	{
		MMatrix mControlLocal = MMatrix::identity;
		MMatrix mControlRestWorld = MMatrix::identity;
		status = readControlInput(hControlInputData, i, mControlLocal, mControlRestWorld);
		CHECK_MSTATUS_AND_RETURN_IT(status);

		const ControlSolveStep step = RigModuleNodeBase::solveControlStep(mControlLocal, mControlRestWorld, mParentDelta);

		// The next control's parent is this control. Its delta is this control's world relative to its own rest.
		mParentDelta = MathUtils::computeDeltaFromRest(mControlRestWorld, step.mWorld);

		RigModuleNodeBase::writeOutputMatrix(hOutputData, i, useLocalMatrix ? step.mWorld : step.mOPM);
	}
	return MStatus::kSuccess;
}

template <typename Derived>
MStatus RigModuleWithControlsNode<Derived>::connectControlToRigModule(
	const MObject& oModule, 
	const MObject& oControl,
	const unsigned int index,
	MDagModifier& dagMod)
{
	MStatus status;
	MPlug pControlMessages(oModule, aControlMessage);

	if (pControlMessages.isNull())
	{
		return MStatus::kFailure;
	}

	MPlug pControlMessageIndex = pControlMessages.elementByLogicalIndex(index, &status);
	CHECK_MSTATUS_AND_RETURN_IT(status);

	MPlug pControlRigModule(oControl, RigControlNode::aRigModule);

	if (pControlRigModule.isNull() || pControlMessageIndex.isNull())
	{
		return MStatus::kFailure;
	}

	return dagMod.connect(pControlMessageIndex, pControlRigModule);
}

template <typename Derived>
MStatus RigModuleWithControlsNode<Derived>::connectControlInputMatrix(
	const MObject& oModule,
	const MObject& oControl,
	unsigned int index,
	MDagModifier& dagMod
)
{
	MPlug pControlInputData(oModule, aControlInputData);

	if (pControlInputData.isNull())
	{
		return MStatus::kFailure;
	}

	MPlug pControlInputDataIndex = pControlInputData.elementByLogicalIndex(index);
	if (pControlInputDataIndex.isNull())
	{
		return MStatus::kFailure;
	}

	MPlug pControlInputMatrix = pControlInputDataIndex.child(aControlMatrix);

	MPlug pControlLocalMatrix(oControl, RigControlNode::matrix);

	if (pControlLocalMatrix.isNull())
	{
		return MStatus::kFailure;
	}


	return dagMod.connect(pControlLocalMatrix, pControlInputMatrix);
	
}

template <typename Derived>
MStatus RigModuleWithControlsNode<Derived>::setControlRestMatrix(
	const MObject& oModule,
	const MMatrix& worldMatrix,
	unsigned int index,
	MDagModifier& dagMod
)
{
	MPlug pControlInputData(oModule, aControlInputData);

	if (pControlInputData.isNull())
	{
		return MStatus::kFailure;
	}

	MPlug pControlInputDataIndex = pControlInputData.elementByLogicalIndex(index);
	if (pControlInputDataIndex.isNull())
	{
		return MStatus::kFailure;
	}

	MPlug pControlRestWorld = pControlInputDataIndex.child(aControlRestWorld);
	return DagUtils::setMatrixPlug(pControlRestWorld, worldMatrix, dagMod);
}

template <typename Derived>
MStatus RigModuleWithControlsNode<Derived>::readControlInput(
	MArrayDataHandle& hControlInputData,
	unsigned int logicalIndex,
	MMatrix& mOutLocal,
	MMatrix& mOutRestWorld)
{
	MStatus status = hControlInputData.jumpToElement(logicalIndex);
	if (!status)
	{
		return status;
	}

	MDataHandle hElement = hControlInputData.inputValue(&status);
	CHECK_MSTATUS_AND_RETURN_IT(status);

	mOutLocal = hElement.child(aControlMatrix).asMatrix();
	mOutRestWorld = hElement.child(aControlRestWorld).asMatrix();
	return MStatus::kSuccess;
}

template <typename Derived>
MMatrix RigModuleWithControlsNode<Derived>::readChildPlugParentDelta(MArrayDataHandle& hChildPlugs, unsigned int logicalIndex)
{
	if (hChildPlugs.jumpToElement(logicalIndex) != MStatus::kSuccess)
	{
		return MMatrix::identity;
	}

	MDataHandle hElement = hChildPlugs.inputValue();
	const MMatrix mParentWorld = hElement.child(aChildPlugParentMatrix).asMatrix();
	const MMatrix mParentRest = hElement.child(aChildPlugParentRestMatrix).asMatrix();
	return MathUtils::computeDeltaFromRest(mParentRest, mParentWorld);

}

template <typename Derived>
MStatus RigModuleWithControlsNode<Derived>::reparentChildPlugToSocket(const RigModuleDagReparentArgs& args)
{
	MStatus status;

	const bool childHasControl = !args.childPlug.oTransform.isNull();
	const bool socketHasControl = !args.parentSocket.oTransform.isNull();
	if (childHasControl && socketHasControl)
	{
		status = args.dagMod.reparentNode(args.childPlug.oTransform, args.parentSocket.oTransform);
		CHECK_MSTATUS_AND_RETURN_IT(status);
	}
	else
	{
		MGlobal::displayWarning(MString("Socket or child plug did not exist for DAG reparent"));  // we no longer have the child plug or parent socket namee
	}

	return connectSocketMatrixToChildPlug(
		args.oChildModuleNode,
		args.childPlug.plugIndex,
		args.oParentTargetModuleNode,
		args.parentSocket.outputIndex,
		args.parentSocket.mRestWorld,
		args.dagMod
	);
}

template <typename Derived>
void RigModuleWithControlsNode<Derived>::declareControlAffects()
{
	const MObject oInputs[] =
	{
		aControlMatrix,
		aControlRestWorld,
		aChildPlugParentMatrix,
		aChildPlugParentRestMatrix
	};
	const MObject oOutputs[] = { aControlOPM, aOutputSocketMatrix };

	for (const MObject& oInput : oInputs)
	{
		for (const MObject& oOutput : oOutputs)
		{
			MPxNode::attributeAffects(oInput, oOutput);
		}
	}
}

template <typename Derived>
MStatus RigModuleWithControlsNode<Derived>::computeChainOutput(
	const MPlug& plug,
	MDataBlock& data,
	bool useWorldMatrix,
	unsigned int childPlugIndex)
{
	MStatus status;

	MArrayDataHandle hControlInputData = data.inputArrayValue(aControlInputData, &status);
	CHECK_MSTATUS_AND_RETURN_IT(status);

	MArrayDataHandle hOutputData = data.outputArrayValue(plug.attribute(), &status);
	CHECK_MSTATUS_AND_RETURN_IT(status);

	status = solveFkChain(data, hControlInputData, hOutputData, childPlugIndex, useWorldMatrix);
	CHECK_MSTATUS_AND_RETURN_IT(status);

	hOutputData.setAllClean();
	data.setClean(plug);
	return MStatus::kSuccess;
}

template <typename Derived>
MStatus RigModuleWithControlsNode<Derived>::wireControl(
	const MObject& oModule,
	const MObject& oControl,
	unsigned int index,
	const MMatrix& mRestWorld,
	MDagModifier& dagMod)
{
	MStatus status;

	status = connectControlInputMatrix(oModule, oControl, index, dagMod);
	CHECK_MSTATUS_AND_RETURN_IT(status);

	// Stored once at build time and never touched again.
	status = setControlRestMatrix(oModule, mRestWorld, index, dagMod);
	CHECK_MSTATUS_AND_RETURN_IT(status);

	status = connectControlToRigModule(oModule, oControl, index, dagMod);
	CHECK_MSTATUS_AND_RETURN_IT(status);

	MPlug pOutputControlOPM(oModule, aControlOPM);
	MPlug pControlOPM(oControl, RigControlNode::offsetParentMatrix);
	return dagMod.connect(pOutputControlOPM.elementByLogicalIndex(index), pControlOPM);
}


template <typename Derived>
class RigModuleWithJointsNode : public RigModuleWithControlsNode<Derived>
{
public:
	using Base = RigModuleWithControlsNode<Derived>;

	inline static MObject aJointOPM;

	static MStatus initializeSharedAttributes();
	static void declareStandardAffects();
};

template <typename Derived>
MStatus RigModuleWithJointsNode<Derived>::initializeSharedAttributes()
{
	MStatus status = Base::initializeSharedAttributes();   // RigModuleWithControlsNode<Derived>
	CHECK_MSTATUS_AND_RETURN_IT(status);

	MFnMatrixAttribute mAttr;
	aJointOPM = mAttr.create(RigAttr::JointOPM, RigAttr::JointOPM, MFnMatrixAttribute::kDouble, &status);
	CHECK_MSTATUS_AND_RETURN_IT(status);
	mAttr.setArray(true);
	mAttr.setWritable(false);
	mAttr.setStorable(false);
	mAttr.setUsesArrayDataBuilder(true);
	return Base::addAttribute(aJointOPM);
}

// Every control/child-plug input affects every control OPM, joint OPM and socket output.
// Call after initializeSharedAttributes() and after any module-specific attributes are added.
template <typename Derived>
void RigModuleWithJointsNode<Derived>::declareStandardAffects()
{
	// controlOPM and outputSocketMatrix
	Base::declareControlAffects();

	// Joint OPM is the only output this layer adds
	const MObject oInputs[] =
	{
		Base::aControlMatrix,
		Base::aControlRestWorld,
		Base::aChildPlugParentMatrix,
		Base::aChildPlugParentRestMatrix
	};
		
	for (const MObject& oInput : oInputs)
	{
		MPxNode::attributeAffects(oInput, aJointOPM);
	}
}
