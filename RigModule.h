// Used so that we don't have to query plugs in our second pass, allowing us to keep the dagMod clean.
struct RigModuleSocketInfo
{
	MObject oTransform;             // The control the DAG parenting targets
	unsigned int outputIndex = 0;   // Logical index into outputSocketMatrix
	MMatrix mRestWorld;             // Socket world matrix at rest
};

struct RigModuleChildPlugInfo
{
	MObject oTransform;             // The control that gets DAG parented
	unsigned int plugIndex = 0;     // Logical index into childPlugs
};

// Common struct for the args used when parenting module plugs.
struct RigModuleDagReparentArgs
{
	RigModuleChildPlugInfo childPlug;
	RigModuleSocketInfo parentSocket;

	MObject oChildModuleNode;
	MObject oParentTargetModuleNode;

	MDagModifier& dagMod;
};

// this has to come before the node because the node uses it
struct RigModuleBuildResult
{
	MStatus status = MStatus::kFailure;
	MObject moduleNode = MObject::kNullObj;

	// Named socket handles generated by the module:
	std::unordered_map<std::string, RigModuleSocketInfo> parentSockets;
	std::unordered_map<std::string, RigModuleChildPlugInfo> childPlugs;

	std::function<MStatus(RigModuleDagReparentArgs args)> dagParentCallback;

	// Evaluates directly as a bool in conditional checks
	explicit operator bool() const { return status == MStatus::kSuccess; }
};

using RigModuleMap = std::unordered_map<std::string, RigModuleBuildResult>;

// Read-phase inputs for one module's plan step.
struct PlanContext
{
	const RigModuleData& moduleData;
	const std::string& where;         // RigTemplateValidation::modulePath, the prefix for report messages
	MarkedJointSet& markedJoints;     // Plan steps resolve [side, usage] args through RigModuleNodeBase::claimJoint
	ValidationReport& report;
};

// One module's read-phase result. Only build touches the dagMod, and it runs after the whole template validated.
struct ModulePlan
{
	std::string name;
	ModuleInterface moduleInterface;   // buildModules checks the built result against this
	// Captures the module's resolved inputs by value, so each module keeps its own typed data
	// without this header knowing every module's input type.
	std::function<RigModuleBuildResult(MObject& oRigRoot, MDagModifier& dagMod)> build;
};

// Aliases so the descriptor reads cleanly. These match what registerNode expects.
using NodeCreatorFn = void* (*)();
using NodeInitializeFn = MStatus(*)();
// Parses moduleArgs, claims joints, reads rest matrices and fills outPlan. Never touches the dagMod.
// Returns false when it reported an error.
using ModulePlanFn = std::function<bool(const nlohmann::json& args, PlanContext& ctx, ModulePlan& outPlan)>;

struct ModuleDescriptor
{
	MString nodeName;       // Maya node type, e.g. "fkChainModule"
	const char* moduleType;     // JSON type, e.g. "FkChain"
	MTypeId typeId;
	NodeCreatorFn creator;
	NodeInitializeFn initialize;
	int currentVersion;
	ModulePlanFn plan;          // nullptr = registered with Maya but not buildable from JSON
};

// Result of solving one control step. Shared by every module that carries controls.
struct ControlSolveStep
{
	MMatrix mOPM;     // Control rest carried by the parent's motion. Excludes the control's local matrix.
	MMatrix mWorld;   // mLocal * mOPM
};

// This class is just a class with shared helper methods for rig module nodes. 
// You CAN NOT have "inheritance" for Maya nodes because of MObject pointers.
