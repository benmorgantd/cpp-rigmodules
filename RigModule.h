// Common struct for the args used when parenting module plugs.
struct RigModuleDagReparentArgs
{
	std::string childPlugName;

	MObject oChildModuleNode;
	MObject oChildPlugTransform;

	MObject oParentTargetTransform;

	MDGModifier& dgMod;
	MDagModifier& dagMod;
};

// this has to come before the node because the node uses it
struct RigModuleBuildResult
{
	MStatus status = MStatus::kFailure;
	MObject moduleNode = MObject::kNullObj;

	// Named socket handles generated by the module:
	std::unordered_map<std::string, MObject> parentSockets;
	std::unordered_map<std::string, MObject> childPlugs;

	std::function<MStatus(RigModuleDagReparentArgs args)> dagParentCallback;

	// Evaluates directly as a bool in conditional checks
	explicit operator bool() const { return status == MStatus::kSuccess; }
};

// This class is just a class with shared helper methods for rig module nodes. 
// You CAN NOT have "inheritance" for Maya nodes because of MObject pointers.
class RigModuleNodeBase : public MPxNode
{
public:
	RigModuleNodeBase();
	virtual ~RigModuleNodeBase() override;
	virtual MStatus compute(const MPlug& plug, MDataBlock& data) override;
public:
	// Data access helpers
	static MMatrix getInputMatrix(MDataBlock& data, const MObject& attr, unsigned int idx);
	static MMatrix getInputMatrix(MDataBlock& data, const MObject& attr);
	static MMatrix getInputCompoundMatrix(
		MDataBlock& data,
		const MObject& aParentCompound,
		const MObject& aChildAttr,
		unsigned int logicalIndex
	);
	static void setOutputMatrix(MDataBlock& data, const MObject& attr, unsigned int idx, const MMatrix& mat);
	static void setOutputMatrix(MDataBlock& data, const MObject& attr, const MMatrix& mat);

	// Matrix calculation & socket parsing helpers
	static MMatrix computeOffsetParentMatrix(const MMatrix& mControlWorld, const MMatrix& mDagParentWorld);
	static int resolveSocketIndex(const MString& key, unsigned int totalElements);
	static MStatus connectParentMatrixToChildPlug(
		MPlug pChildPlugs,
		const MObject& oTargetSocketTransform,
		const MString& targetChildPlugName,
		MDGModifier& dgMod
	);
public:
	// Shared creation & build methods
	static MStatus initializeSharedAttributes(MObject& moduleData, MObject& aRigRoot, MObject& aRigControls, MObject& aOutputSocketMatrix, MObject& aSide);
	static MStatus connectModuleToRigRoot(MObject& oRigRoot, MDGModifier& dgMod, const MObject& oModule, MObject& aRigRoot);
	static std::unordered_map<std::string, RigModuleBuildResult> buildModules(const std::vector<RigModuleData>& flatModuleList, MObject oRigRoot, MDGModifier& dgMod, MDagModifier& dagMod);
	static MObject findPlugOrSocketTransform(const std::unordered_map<std::string, MObject>& socketPairs, const std::string& name);
};

