{
	const MObject oInputs[] =
	{
		aControlMatrix,
		aControlRestWorld,
		aChildPlugParentMatrix,
		aChildPlugParentRestMatrix
	};
	const MObject oOutputs[] = { aControlOPM, aOutputSocketMatrix };

	for (const MObject& oInput : oInputs)
	{
		for (const MObject& oOutput : oOutputs)
		{
			MPxNode::attributeAffects(oInput, oOutput);
		}
	}
}

template <typename Derived>
MStatus RigModuleWithControlsNode<Derived>::computeChainOutputs(
	const MPlug& plug,
	MDataBlock& data,
	const MObject& oJointOPM,
	unsigned int childPlugIndex)
{
	MStatus status;

	MArrayDataHandle hControlInputData = data.inputArrayValue(aControlInputData, &status);
	CHECK_MSTATUS_AND_RETURN_IT(status);

	MArrayDataHandle hControlOPM = data.outputArrayValue(aControlOPM, &status);
	CHECK_MSTATUS_AND_RETURN_IT(status);
	MArrayDataHandle hSocket = data.outputArrayValue(aOutputSocketMatrix, &status);
	CHECK_MSTATUS_AND_RETURN_IT(status);

	const bool hasJoints = !oJointOPM.isNull();
	MArrayDataHandle hJointOPM = hasJoints ? data.outputArrayValue(oJointOPM, &status) : hControlOPM;
	CHECK_MSTATUS_AND_RETURN_IT(status);

	status = solveFkChain(data, hControlInputData, hControlOPM, hSocket, hasJoints ? &hJointOPM : nullptr, childPlugIndex);
	CHECK_MSTATUS_AND_RETURN_IT(status);

	const MObject oNode = plug.node();
	commitOutput(data, oNode, aControlOPM, hControlOPM);
	commitOutput(data, oNode, aOutputSocketMatrix, hSocket);
	if (hasJoints)
	{
		commitOutput(data, oNode, oJointOPM, hJointOPM);
	}
	data.setClean(plug);
	return MStatus::kSuccess;
}

template <typename Derived>
void RigModuleWithControlsNode<Derived>::commitOutput(MDataBlock& data, const MObject& oNode, const MObject& oAttr, MArrayDataHandle& hOutput)
{
	hOutput.setAllClean();
	data.setClean(MPlug(oNode, oAttr));
}

template <typename Derived>
MStatus RigModuleWithControlsNode<Derived>::readControlInputs(
	MArrayDataHandle& hControlInputData,
	unsigned int firstSlot,
	unsigned int count,
	MMatrix* mOutLocal,
	MMatrix* mOutRestWorld)
{
	for (unsigned int i = 0; i < count; ++i)
	{
		const MStatus status = readControlInput(hControlInputData, firstSlot + i, mOutLocal[i], mOutRestWorld[i]);
		CHECK_MSTATUS_AND_RETURN_IT(status);
	}
	return MStatus::kSuccess;
}

template <typename Derived>
SolvedOutputs RigModuleWithControlsNode<Derived>::openSolvedOutputs(MDataBlock& data, const MObject& oJointOPM, MStatus& status)
{
	MStatus controlStatus;
	MStatus jointStatus;
	MStatus socketStatus;
	SolvedOutputs outputs
	{
		data.outputArrayValue(aControlOPM, &controlStatus),
		data.outputArrayValue(oJointOPM, &jointStatus),
		data.outputArrayValue(aOutputSocketMatrix, &socketStatus)
	};
	status = !controlStatus ? controlStatus : !jointStatus ? jointStatus : socketStatus;
	return outputs;
}

template <typename Derived>
void RigModuleWithControlsNode<Derived>::writeSolvedSlot(
	SolvedOutputs& outputs,
	unsigned int slot,
	const MMatrix& mControlOPM,
	const MMatrix& mWorld,
	bool hasSocket)
{
	RigModuleNodeBase::writeOutputMatrix(outputs.hControlOPM, slot, mControlOPM);
	RigModuleNodeBase::writeOutputMatrix(outputs.hJointOPM, slot, mWorld);
	if (hasSocket)
	{
		RigModuleNodeBase::writeOutputMatrix(outputs.hSocket, slot, mWorld);
	}
}

template <typename Derived>
void RigModuleWithControlsNode<Derived>::commitSolvedOutputs(MDataBlock& data, const MPlug& plug, const MObject& oJointOPM, SolvedOutputs& outputs)
{
	const MObject oNode = plug.node();
	commitOutput(data, oNode, aControlOPM, outputs.hControlOPM);
	commitOutput(data, oNode, oJointOPM, outputs.hJointOPM);
	commitOutput(data, oNode, aOutputSocketMatrix, outputs.hSocket);
	data.setClean(plug);
}

template <typename Derived>
MStatus RigModuleWithControlsNode<Derived>::wireControl(
	const MObject& oModule,
	const MObject& oControl,
	unsigned int index,
	const MMatrix& mRestWorld,
	MDagModifier& dagMod)
{
	MStatus status;

	status = connectControlInputMatrix(oModule, oControl, index, dagMod);
	CHECK_MSTATUS_AND_RETURN_IT(status);

	// Stored once at build time and never touched again.
	status = setControlRestMatrix(oModule, mRestWorld, index, dagMod);
	CHECK_MSTATUS_AND_RETURN_IT(status);

	status = connectControlToRigModule(oModule, oControl, index, dagMod);
	CHECK_MSTATUS_AND_RETURN_IT(status);

	MPlug pOutputControlOPM(oModule, aControlOPM);
	MPlug pControlOPM(oControl, RigControlNode::offsetParentMatrix);
	return dagMod.connect(pOutputControlOPM.elementByLogicalIndex(index), pControlOPM);
}


template <typename Derived>
class RigModuleWithJointsNode : public RigModuleWithControlsNode<Derived>
{
public:
	using Base = RigModuleWithControlsNode<Derived>;

	inline static MObject aJointOPM;
	// Each driven joint's world matrix at build time, by the same index as jointOPM. Stored data only: compute
	// never reads it, so it affects nothing. Skin weight loading binds new influences at this rest (D35).
	inline static MObject aJointRestWorld;

	static MStatus initializeSharedAttributes();
	static void declareStandardAffects();

	// Hands the joint to the module: turns off inheritsTransform and segment scale compensate, bakes mRestWorld
	// into its OPM, stores the rest and connects jointOPM[index] to the joint's offsetParentMatrix.
	static MStatus wireJoint(const MObject& oModule, MObject oJoint, unsigned int index, const MMatrix& mRestWorld, MDagModifier& dagMod);
};

template <typename Derived>
MStatus RigModuleWithJointsNode<Derived>::initializeSharedAttributes()
{
	MStatus status = Base::initializeSharedAttributes();   // RigModuleWithControlsNode<Derived>
	CHECK_MSTATUS_AND_RETURN_IT(status);

	MFnMatrixAttribute mAttr;
	aJointOPM = mAttr.create(RigAttr::JointOPM, RigAttr::JointOPM, MFnMatrixAttribute::kDouble, &status);
	CHECK_MSTATUS_AND_RETURN_IT(status);
	mAttr.setArray(true);
	mAttr.setWritable(false);
	mAttr.setStorable(false);
	mAttr.setUsesArrayDataBuilder(true);
	status = Base::addAttribute(aJointOPM);
	CHECK_MSTATUS_AND_RETURN_IT(status);

	aJointRestWorld = mAttr.create(RigAttr::JointRestWorld, RigAttr::JointRestWorld, MFnMatrixAttribute::kDouble, &status);
	CHECK_MSTATUS_AND_RETURN_IT(status);
	mAttr.setArray(true);
	mAttr.setStorable(true);
	mAttr.setUsesArrayDataBuilder(true);
	return Base::addAttribute(aJointRestWorld);
}

template <typename Derived>
MStatus RigModuleWithJointsNode<Derived>::wireJoint(
	const MObject& oModule,
	MObject oJoint,
	unsigned int index,
	const MMatrix& mRestWorld,
	MDagModifier& dagMod)
{
	MStatus status;
	MFnDependencyNode fnJoint(oJoint);
	MPlug pJointRestWorld = MPlug(oModule, aJointRestWorld).elementByLogicalIndex(index);

	// The module drives the joint's world transform through its OPM, so nothing may be inherited.
	DagUtils::setInheritsTransform(oJoint, false, dagMod);
	DagUtils::setSegmentScaleCompensate(oJoint, false, dagMod);
	status = DagUtils::bakeJointTransformsToOPM(oJoint, mRestWorld, dagMod);
	if (!status)
	{
		MGlobal::displayError(MString("Failed to bake the joint into its offsetParentMatrix: ") + fnJoint.name());
		return status;
	}

	status = DagUtils::setMatrixPlug(pJointRestWorld, mRestWorld, dagMod);
	CHECK_MSTATUS_AND_RETURN_IT(status);

	return dagMod.connect(MPlug(oModule, aJointOPM).elementByLogicalIndex(index), MPlug(oJoint, MPxTransform::offsetParentMatrix));
}

// Every control/child-plug input affects every control OPM, joint OPM and socket output.
// Call after initializeSharedAttributes() and after any module-specific attributes are added.
template <typename Derived>
void RigModuleWithJointsNode<Derived>::declareStandardAffects()
{
	// controlOPM and outputSocketMatrix
	Base::declareControlAffects();

	// Joint OPM is the only output this layer adds
	const MObject oInputs[] =
	{
		Base::aControlMatrix,
		Base::aControlRestWorld,
		Base::aChildPlugParentMatrix,
		Base::aChildPlugParentRestMatrix
	};
		
	for (const MObject& oInput : oInputs)
	{
		MPxNode::attributeAffects(oInput, aJointOPM);
	}
}
